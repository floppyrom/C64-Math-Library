#!/usr/bin/env python3
"""Publish complete ACME sources, including tables, for the optional kernels."""
from __future__ import annotations

import argparse
from pathlib import Path

from tables import build_tables, build_sum_tables, build_sum_small_tables

HERE = Path(__file__).resolve().parent
OPTIMIZED = ('compact_opt', 'sum_small', 'sum_fast')


def table_blocks(kind: str):
    if kind == 'compact_opt':
        log, angle, *_ = build_tables()
        return (('LOGTAB', log), ('ATANTAB', angle))
    if kind == 'sum_small':
        return tuple(zip(('LOGX', 'LOGY', 'QPOS'), build_sum_small_tables()))
    if kind == 'sum_fast':
        return tuple(zip(('LOGX', 'LOGY', 'QPOS', 'QNEG'), build_sum_tables()))
    raise ValueError(kind)


def export_source(kind: str) -> str:
    body = (HERE / f'atan2_{kind}.asm').read_text().replace(
        '.org @ORG@', '* = ATAN2_CODE')
    header = f'''; C64 Math Library: optional {kind} ATAN2 kernel, WITH all required tables.
; GENERATED by routines/atan2/export_optimized.py; edit the canonical source.
; Assemble: acme -f cbm -o atan2.prg atan2_s8_s8_u8_{kind}.asm
; Load the PRG, bank RAM in as necessary, and JSR atan2_s8_s8_u8.
; X0/Y0/Z0 are memory addresses, not CPU registers. Set D=0 before calling.
; No initialization, ZP, scratch, self-modifying code, or extra stack is needed.
; The only stack use is the caller's ordinary two-byte JSR return address.
; To relocate, edit ATAN2_CODE, PUBLIC_ENTRY, X0/Y0/Z0 and the table constants.
; Keep tables page aligned and all code/data/I/O/stack regions disjoint.
; Use page-aligned ATAN2_CODE for the published cycle counts.
; This standalone layout is NOT an overlay for the shipped resident profiles.
!cpu 6502
ATAN2_CODE = $8000
PUBLIC_ENTRY = $7F00
* = PUBLIC_ENTRY
atan2_s8_s8_u8:
    jmp atan2

'''
    data = []
    for name, values in table_blocks(kind):
        data.append(f'\n!if ({name} & $ff) != 0 {{ !error "{name} must be page aligned" }}\n')
        data.append(f'* = {name}\n')
        for offset in range(0, len(values), 16):
            data.append('    !byte ' + ','.join(f'${v:02X}' for v in values[offset:offset + 16]) + '\n')
    return header + body + ''.join(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify committed exports without rewriting')
    args = parser.parse_args()
    outdir = HERE / 'standalone'
    if not args.check:
        outdir.mkdir(exist_ok=True)
    for kind in OPTIMIZED:
        path = outdir / f'atan2_s8_s8_u8_{kind}.asm'
        expected = export_source(kind)
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'stale or missing export: {path}')
        else:
            path.write_text(expected)
        print(('checked' if args.check else 'wrote'), path.relative_to(HERE))


if __name__ == '__main__':
    main()
